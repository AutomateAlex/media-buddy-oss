def _text(value: Any) -> str:
    return str(value or "").strip()


def _tokenize(text: str) -> list[str]:
    raw = re.findall(r"[A-Za-z0-9_\-]+|[\u4e00-\u9fff]{2,}", text)
    tokens: list[str] = []
    for token in raw:
        t = token.lower().strip()
        if len(t) < 2 or t in _COMMON_WORDS:
            continue
        tokens.append(t)
    return tokens


def _cjk_bigrams(text: str) -> set[str]:
    chars = re.findall(r"[\u4e00-\u9fff]", _text(text))
    return {"".join(chars[i:i + 2]) for i in range(max(0, len(chars) - 1))}


_GENERIC_DUPLICATE_PHRASES = {
    "为什么", "是什么", "怎么做", "怎么样", "真正", "到底", "不是", "视频", "科普",
    "知识", "故事", "真相", "解析", "频道", "长视频", "短视频", "一个", "这种",
}


def _longest_cjk_common_substring(a: str, b: str) -> str:
    a_chars = "".join(re.findall(r"[\u4e00-\u9fff]", _text(a)))
    b_chars = "".join(re.findall(r"[\u4e00-\u9fff]", _text(b)))
    if not a_chars or not b_chars:
        return ""
    best = ""
    for i in range(len(a_chars)):
        for j in range(i + max(3, len(best) + 1), len(a_chars) + 1):
            piece = a_chars[i:j]
            if piece in b_chars and piece not in _GENERIC_DUPLICATE_PHRASES:
                best = piece
    return best


def _channel_rule_from_json(data: Any) -> ChannelRule | None:
    """把 Series.channel_rule_json(AI 为自定义频道生成的规则)重建成 ChannelRule。

    容错:缺失/None 字段回落 ChannelRule 默认值;list→tuple。若既无 positioning 也无
    anchors(空壳)返回 None —— 宁可退回通用路径(check_fit 的 unknown 分支),也不要一个
    会静默退化的空规则。"""
    if not isinstance(data, dict):
        return None

    def _tup(key: str) -> tuple[str, ...]:
        v = data.get(key)
        if isinstance(v, (list, tuple)):
            return tuple(str(x).strip() for x in v if str(x).strip())
        return ()

    positioning = _text(data.get("positioning"))
    anchors = _tup("anchors")
    if not positioning and not anchors:
        return None
    return ChannelRule(
        label=_text(data.get("label")) or "自定义频道",
        anchors=anchors,
        off_domain=_tup("off_domain"),
        recommendations=_tup("recommendations"),
        subjects=_tup("subjects"),
        angle_templates=_tup("angle_templates"),
        positioning=positioning,
        concept_channel=bool(data.get("concept_channel", False)),
        closure_rule=_text(data.get("closure_rule")),
    )


