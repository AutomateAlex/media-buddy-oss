    def check_duplicate(self, db: Session, series_id: str, idea: str) -> dict[str, Any]:
        series = self._get_series(db, series_id)
        projects = self._projects(db, series_id)
        dedupe_idea = _dedupe_subject(idea)
        matches: list[dict[str, Any]] = []
        for p in projects:
            project_subject = _dedupe_subject(_project_text(p))
            score = _similarity(dedupe_idea, project_subject)
            if score >= 0.34:
                matches.append({
                    "project_id": p.id,
                    "title": p.name,
                    "status": p.status,
                    "score": round(score, 3),
                })
        matches.sort(key=lambda x: x["score"], reverse=True)
        top = matches[0]["score"] if matches else 0.0
        risk = "high" if top >= 0.62 else "medium" if top >= 0.42 else "low"
        return {
            "series_id": series.id,
            "idea": idea,
            "risk": risk,
            "is_duplicate": risk == "high",
            "matches": matches[:5],
            "guidance": (
                "这个选题和频道内已有项目太接近，建议换角度。"
                if risk == "high"
                else "有一点相似，建议换标题钩子或切入角度。"
                if risk == "medium"
                else "没有明显重复，可以继续。"
            ),
        }

