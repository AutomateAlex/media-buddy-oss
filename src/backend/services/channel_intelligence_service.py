def design_channel_rule(description: str, output_language: str = "zh") -> dict[str, Any]:
    """

    返回:
      成功 → {"ok": True, "name": str, "director_prompt": str, "rule": {ChannelRule dict}}
      违规 → {"ok": False, "policy": str, "reason": str}
    ②LLM 兜底判定新造政治/违法措辞;③生成后再对 positioning+subjects 跑一次词表。
    生成为空/彻底失败 → 抛异常,由调用方转 502。"""
    desc = _text(description).strip()
    if not desc:
        return {"ok": False, "policy": "empty", "reason": "请先描述你想做的频道方向。"}
    if len(desc) > 2000:
        desc = desc[:2000]

    # ① 词表硬闸(主闸):命中中国政治即拒。
    violation = content_policy_violation(None, desc)
    if violation:
        return {"ok": False, "policy": violation["policy"], "reason": violation["reason"]}

    from backend.lib.llm_client import LLMClient
    client = LLMClient()

    # ② LLM 兜底红线判定(补词表漏掉的新说法)。
    guard = _llm_content_guard(client, desc)
    if guard:
        return {"ok": False, "policy": guard["policy"], "reason": guard["reason"]}

    # ③ 生成频道规则。
    lang_hint = "英文" if str(output_language or "zh").lower() == "en" else "中文"
    user = (
        f"用户想做的频道方向:\n{desc}\n\n"
        f"(该频道最终出片语言为{lang_hint},但你的规则文字仍一律写简体中文。)\n"
        "据此设计整套频道智能规则,按系统指定的 JSON 结构输出。"
    )
    raw = client._call(_CHANNEL_DESIGN_SYSTEM, user, purpose="channel_design")
    data = _json_obj(raw) or {}
    rule_raw = data.get("rule") if isinstance(data.get("rule"), dict) else data
    built = _channel_rule_from_json(rule_raw)
    if built is None:
        raise ValueError("channel_design_empty")

    # ④ 生成后词表复查 —— 只查具体选题种子(subjects + recommendations)。
    # 【不查 positioning】:频道纲领常含"🚫绝不出现中国军方/中国政治…"这类【禁止句】,
    # "绝不出现中国军方未证实目击"而被误杀)。用户意图的政治性已由 ② LLM 判官把关,每条真实
    # 选题下游 recommend_topics 还会逐条过 content_policy_violation。subjects/recs 是短实体名/
    # 标题,正是词表子串匹配的适用场景。
    check_text = "\n".join([" ".join(built.subjects), " ".join(built.recommendations)])
    post = content_policy_violation(None, check_text)
    if post:
        return {"ok": False, "policy": post["policy"], "reason": post["reason"]}

    rule_out = {
        "label": built.label,
        "positioning": built.positioning,
        "anchors": list(built.anchors),
        "off_domain": list(built.off_domain),
        "subjects": list(built.subjects),
        "angle_templates": list(built.angle_templates),
        "recommendations": list(built.recommendations),
        "concept_channel": built.concept_channel,
        "closure_rule": built.closure_rule,
    }
    name = _text(data.get("name")) or built.label
    director_prompt = _text(data.get("director_prompt"))
    return {"ok": True, "name": name, "director_prompt": director_prompt, "rule": rule_out}


