def _dedupe_subject(text: str) -> str:
    source = _text(text)
    if not source:
        return ""
    # 主题行优先,中英都认:"主题：X" / "Topic: X"。批量 prompt 一定有这行,
    # 抽出来就是真题目。
    for line in source.splitlines():
        match = re.search(r"(?:主题|主題|topic)\s*[:：]\s*(.+)", line.strip(), re.IGNORECASE)
        if match:
            return match.group(1).strip()
    # 否则取头两行有效内容,跳过中英文样板行。关键:批量 prompt 的样板话
    # ("请在频道…"/"Please produce…"/"Channel positioning…"/"Requirement…")若不过滤,
    # 每条项目都会 collapse 成同一句模板,导致查重把所有项目误判成互相重复(409 根因)。
    boiler_prefix = (
        "请在频道", "频道定位", "要求", "平台", "格式",
        "please produce", "channel positioning", "requirement",
        "platform", "format", "make one", "produce one",
    )
    boiler_contains = (
        "频道定位", "自动查重", "不要串台",
        "channel positioning", "auto-check for duplicates", "switch to a fresh angle",
        "cross channels", "don't cross", "do not cross",
    )
    useful: list[str] = []
    for line in source.splitlines():
        line = line.strip()
        if not line:
            continue
        low = line.lower()
        if low.startswith(boiler_prefix):
            continue
        if any(b in low for b in boiler_contains):
            continue
        useful.append(line)
        if len(useful) >= 2:
            break
    return "\n".join(useful).strip() or source[:160]


def _similarity(a: str, b: str) -> float:
    a = _text(a)
    b = _text(b)
    if not a or not b:
        return 0.0
    ratio = SequenceMatcher(None, a[:600], b[:600]).ratio()
    a_tokens = set(_tokenize(a))
    b_tokens = set(_tokenize(b))
    overlap = len(a_tokens & b_tokens) / max(1, min(len(a_tokens), len(b_tokens)))
    a_bigrams = _cjk_bigrams(a)
    b_bigrams = _cjk_bigrams(b)
    cjk_overlap = len(a_bigrams & b_bigrams) / max(1, min(len(a_bigrams), len(b_bigrams)))
    score = max(ratio, overlap, cjk_overlap)
    core_phrase = _longest_cjk_common_substring(a, b)
    if len(core_phrase) >= 4 and cjk_overlap >= 0.28:
        score = max(score, 0.66)
    elif len(core_phrase) >= 3 and cjk_overlap >= 0.42:
        score = max(score, 0.62)
    return score


