def _json_obj(raw: str) -> dict:
    """Extract the first JSON object from an LLM response."""
    import json
    try:
        s = raw[raw.index("{"): raw.rindex("}") + 1]
        d = json.loads(s)
        return d if isinstance(d, dict) else {}
    except Exception:
        return {}


@dataclass(frozen=True)
class ChannelRule:
    label: str
    anchors: tuple[str, ...]
    off_domain: tuple[str, ...] = ()
    recommendations: tuple[str, ...] = ()
    # 组合池:subjects × angle_templates(模板含 {s})→ 几百种选题,随机抽,
    # 同主体不同角度=讲解点也不同。耗尽后再走 LLM 现场生成(真无限)。
    subjects: tuple[str, ...] = ()
    angle_templates: tuple[str, ...] = ()
    # 频道定位(喂给 LLM 现场脑暴的"频道是什么·要什么调性·避什么")。设了就覆盖
    # 内置频道的 series.description,让 AI 严格围绕这套定位选题。留空=沿用旧逻辑。
    positioning: str = ""
    # 概念/观点类频道(金钱认知/心理/成长等)。True=选题是【普世概念/现象/心理】,
    # 不绑地理实体——关掉"选题主体面向全世界·具体到某城市/案例"的 geo 硬规则,
    # 否则 AI 会把概念硬套成"德国某咖啡馆""美国某居民"这种做作的外国小故事。
    concept_channel: bool = False
    # 收口标准:这个频道的片子"讲完了"是什么样。喂给收口判断器当裁判依据。
    # 留空 → 用 closure_standards.DEFAULT_CLOSURE_RULE(知识科普口径)。
    # 之所以放这里而不另建配置文件:频道该怎么收尾本就是频道定位的一部分,
    # positioning 里很多频道已经写了(如 mystery_explainer 的"结尾给出最可信的
    # 主流解释")。另起一份配置 = 双事实源,改一处忘一处。
    closure_rule: str = ""


